// Converts the Cloudflare Pages-style dist/_headers (written by the build, with the CSP script hash
// filled in) into nginx `add_header` lines, so a Docker/nginx deploy sends the same security headers.
// Usage: node scripts/headers-to-nginx.mjs dist/_headers /path/to/security-headers.conf
import fs from "node:fs";

const [, , input, output] = process.argv;
if (!input || !output) {
  console.error("usage: headers-to-nginx.mjs <_headers> <output.conf>");
  process.exit(2);
}

// Only the `/*` block applies to every response; cache rules live in nginx.conf.
const headers = [];
let current = null;
for (const raw of fs.readFileSync(input, "utf8").split(/\r?\n/)) {
  if (!raw.trim() || raw.trim().startsWith("#")) continue;
  if (!/^\s/.test(raw)) {
    current = raw.trim();
    continue;
  }
  if (current !== "/*") continue;
  const i = raw.indexOf(":");
  headers.push([raw.slice(0, i).trim(), raw.slice(i + 1).trim()]);
}

const need = ["Content-Security-Policy", "X-Content-Type-Options", "Referrer-Policy", "Permissions-Policy"];
for (const name of need) {
  if (!headers.some(([n]) => n.toLowerCase() === name.toLowerCase())) throw new Error(`${name} missing from ${input}`);
}
const csp = headers.find(([n]) => n === "Content-Security-Policy")[1];
if (/__[A-Z_]+__/.test(csp)) throw new Error("CSP still has an unfilled placeholder");
if (!/'sha256-[A-Za-z0-9+/=]+'/.test(csp)) throw new Error("CSP has no script hash for the inline boot script");

const lines = headers.map(([name, value]) => {
  if (/["\\$\n]/.test(value)) throw new Error(`${name}: value has a character that needs escaping in nginx`);
  return `add_header ${name} "${value}" always;`;
});
fs.writeFileSync(output, `# Generated by scripts/headers-to-nginx.mjs from dist/_headers. Do not edit.\n${lines.join("\n")}\n`);
console.log(`${lines.length} security headers written to ${output}`);
