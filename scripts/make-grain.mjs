// Writes src/styles/grain.css: a 128px pre-rendered noise tile as an inline PNG data URI.
// main.ts loads it lazily on Tier A only, so it never weighs on the render-blocking CSS.
// The design system bans live feTurbulence (slow on phones). 2-bit grayscale keeps the
// tile ~4 KB; at 4% opacity it is indistinguishable from 8-bit noise. Run: node scripts/make-grain.mjs
import fs from "node:fs";
import zlib from "node:zlib";

const SIZE = 128;
let seed = 0x9e3779b9;
const rand = () => {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return (seed >>> 0) / 4294967296;
};

// Raw scanlines: filter byte 0, then 4 pixels per byte (2 bits each).
const rowBytes = SIZE / 4;
const raw = Buffer.alloc((rowBytes + 1) * SIZE);
for (let y = 0; y < SIZE; y++) {
  raw[y * (rowBytes + 1)] = 0;
  for (let x = 0; x < rowBytes; x++) {
    let byte = 0;
    for (let k = 0; k < 4; k++) byte = (byte << 2) | Math.floor(rand() * 4);
    raw[y * (rowBytes + 1) + 1 + x] = byte;
  }
}

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(SIZE, 0);
ihdr.writeUInt32BE(SIZE, 4);
ihdr[8] = 2; // bit depth
ihdr[9] = 0; // grayscale
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk("IHDR", ihdr),
  chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
  chunk("IEND", Buffer.alloc(0)),
]);

const css = `/* Generated by scripts/make-grain.mjs — do not edit. ${SIZE}px 2-bit noise tile (${png.length} bytes). */
[data-tier="A"] .grain {
  display: block;
  background-image: url("data:image/png;base64,${png.toString("base64")}");
  background-size: ${SIZE}px ${SIZE}px;
}
`;
fs.writeFileSync("src/styles/grain.css", css);
console.log(`src/styles/grain.css written (${png.length} byte PNG)`);
